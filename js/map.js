/* Fill polygons into a W x H grid using an even-odd scanline. */
M.raster=function(W,H){
  var g=new Uint8Array(W*H);
  function toX(lon){ return (lon+180)/360*W; } function toY(lat){ return (90-lat)/180*H; }
  function fill(poly,val){
    var pts=poly.map(function(p){ return [toX(p[0]),toY(p[1])]; });
    var minY=Math.max(0,Math.floor(Math.min.apply(null,pts.map(function(p){return p[1];})))), maxY=Math.min(H-1,Math.ceil(Math.max.apply(null,pts.map(function(p){return p[1];}))));
    for(var y=minY;y<=maxY;y++){
      var yc=y+0.5, xs=[];
      for(var i=0;i<pts.length;i++){ var a=pts[i], b=pts[(i+1)%pts.length]; if((a[1]<=yc&&b[1]>yc)||(b[1]<=yc&&a[1]>yc)){ xs.push(a[0]+(yc-a[1])/(b[1]-a[1])*(b[0]-a[0])); } }
      xs.sort(function(p,q){return p-q;});
      for(i=0;i+1<xs.length;i+=2){ var x0=Math.max(0,Math.round(xs[i])), x1=Math.min(W-1,Math.round(xs[i+1])); for(var x=x0;x<x1;x++) g[y*W+x]=val; }
    }
  }
  M.LAND.forEach(function(p){ fill(p,1); });
  M.LAKES.forEach(function(p){ fill(p,0); });
  return g;
};
/* Where the sun is right now: returns [lon,lat] of the point directly under the sun. */
M.subsolar=function(date){
  var d=date||new Date(), start=Date.UTC(d.getUTCFullYear(),0,0), doy=(d.getTime()-start)/86400000;
  var decl=-23.44*Math.cos(2*Math.PI/365*(doy+10));
  var utcH=d.getUTCHours()+d.getUTCMinutes()/60+d.getUTCSeconds()/3600;
  var lon=(12-utcH)*15; while(lon>180) lon-=360; while(lon<-180) lon+=360;
  return [lon,decl];
};
/* Sun height above the horizon (−1..1 ish) at a lon/lat for a sub-solar point. */
M.sunUp=function(lon,lat,ss){
  var toR=Math.PI/180, la=lat*toR, dl=ss[1]*toR, h=(lon-ss[0])*toR;
  return Math.sin(la)*Math.sin(dl)+Math.cos(la)*Math.cos(dl)*Math.cos(h);
};
